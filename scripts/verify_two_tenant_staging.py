"""Staging-only read-only two-tenant Cognito OBO isolation verifier.

This does not create users, modify orders, or execute refunds. Its bearer
tokens must be independently minted by real Cognito/AgentCore Identity flows,
not generated by the test. Run only against approved synthetic staging data.
The output never contains token values, order IDs, or response bodies.
"""
from __future__ import annotations

import argparse
import json
import os
from dataclasses import dataclass
from uuid import uuid4
from typing import Any, Callable

from scripts.smoke_agentcore_staging import STAGING_BASE, Response, send


@dataclass(frozen=True)
class StagingIdentity:
    label: str
    token: str
    owned_order: str


def _valid_identity(identity: StagingIdentity) -> bool:
    return (
        bool(identity.token)
        and 1 <= len(identity.owned_order) <= 128
        and all(ch.isalnum() or ch in "-_" for ch in identity.owned_order)
    )


def _public_denial(result: dict[str, Any]) -> dict[str, Any]:
    # IDs are nondeterministic; compare only public semantic structure.
    return {
        key: value for key, value in result.items()
        if key not in {"request_id", "trace_id"}
    }


def check_isolation(
    *,
    tenant_a: StagingIdentity,
    tenant_b: StagingIdentity,
    operator_token: str,
    sender: Callable = send,
) -> tuple[bool, list[str]]:
    if (
        not all((_valid_identity(tenant_a), _valid_identity(tenant_b), operator_token))
        or tenant_a.token == tenant_b.token
        or tenant_a.owned_order == tenant_b.owned_order
    ):
        return False, ["BLOCKED distinct synthetic tenant identities and owned orders required"]
    checks: list[str] = []
    all_ok = True
    missing = "not-present-" + uuid4().hex

    def request_order(who: StagingIdentity, order: str, *, expect: str, label: str):
        nonlocal all_ok
        trace = str(uuid4())
        response: Response = sender(
            STAGING_BASE, "POST", "/v1/agent/tools/get_order",
            token=who.token,
            payload={
                "trace_id": trace,
                "request_id": str(uuid4()),
                "arguments": {"order_id": order},
            },
        )
        try:
            data = json.loads(response.body)
        except (UnicodeError, ValueError, TypeError):
            data = {}
        if not isinstance(data, dict):
            data = {}
        passed = (
            response.status == 200
            and data.get("decision") == expect
            and data.get("trace_id") == trace
        )
        if expect == "ALLOW":
            passed = passed and isinstance(data.get("order"), dict)
        if expect == "DENY":
            passed = (
                passed
                and data.get("reason_code") == "RESOURCE_NOT_AVAILABLE"
                and "order" not in data
                and "eligibility" not in data
                and "approval" not in data
            )
        checks.append(("PASS " if passed else "FAIL ") + label)
        all_ok = all_ok and passed
        return trace, data

    own_a, _ = request_order(tenant_a, tenant_a.owned_order, expect="ALLOW", label="tenant A own order")
    own_b, _ = request_order(tenant_b, tenant_b.owned_order, expect="ALLOW", label="tenant B own order")
    cross_a, denied_a = request_order(tenant_a, tenant_b.owned_order, expect="DENY", label="tenant A cannot read B")
    cross_b, denied_b = request_order(tenant_b, tenant_a.owned_order, expect="DENY", label="tenant B cannot read A")
    _, absent_a = request_order(tenant_a, missing, expect="DENY", label="tenant A missing order not disclosed")
    _, absent_b = request_order(tenant_b, missing, expect="DENY", label="tenant B missing order not disclosed")

    for label, foreign, missing_result in (
        ("tenant A foreign/missing indistinguishable", denied_a, absent_a),
        ("tenant B foreign/missing indistinguishable", denied_b, absent_b),
    ):
        ok = bool(foreign and missing_result) and _public_denial(foreign) == _public_denial(missing_result)
        checks.append(("PASS " if ok else "FAIL ") + label)
        all_ok = all_ok and ok

    for label, trace, decision in (
        ("tenant A allow audited", own_a, "ALLOW"),
        ("tenant B allow audited", own_b, "ALLOW"),
        ("tenant A cross-tenant deny audited", cross_a, "DENY"),
        ("tenant B cross-tenant deny audited", cross_b, "DENY"),
    ):
        response = sender(STAGING_BASE, "GET", "/v1/operator/audit/trace/" + trace,
                          token=operator_token)
        try:
            events = json.loads(response.body)
        except (UnicodeError, ValueError, TypeError):
            events = []
        ok = (
            response.status == 200 and isinstance(events, list) and any(
                isinstance(event, dict)
                and event.get("event_type") == "POLICY_DECISION"
                and event.get("decision") == decision
                and isinstance(event.get("details"), dict)
                and event["details"].get("tool_name") == "get_order"
                for event in events
            )
        )
        checks.append(("PASS " if ok else "FAIL ") + label)
        all_ok = all_ok and ok
    return all_ok, checks


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--run-read-only", action="store_true",
        help="Explicitly run a bounded staging test (10 protected requests)",
    )
    args = parser.parse_args(argv)
    if not args.run_read_only:
        print("NOT RUN: pass --run-read-only to authorize the staging checks")
        return 2
    a = StagingIdentity(
        "A", os.environ.get("SHADOW_HUNTER_E2E_TENANT_A_OBO_JWT", ""),
        os.environ.get("SHADOW_HUNTER_E2E_TENANT_A_ORDER_ID", ""),
    )
    b = StagingIdentity(
        "B", os.environ.get("SHADOW_HUNTER_E2E_TENANT_B_OBO_JWT", ""),
        os.environ.get("SHADOW_HUNTER_E2E_TENANT_B_ORDER_ID", ""),
    )
    try:
        passed, lines = check_isolation(
            tenant_a=a, tenant_b=b,
            operator_token=os.environ.get("SHADOW_HUNTER_E2E_OPERATOR_JWT", ""),
        )
    except (ValueError, OSError, TimeoutError):
        print("FAIL staging boundary request could not complete")
        return 2
    for line in lines:
        print(line)
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
